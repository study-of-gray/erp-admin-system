// scripts/strip-coverage-timestamp.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const coverageDir = path.resolve(__dirname, '../coverage')

if (!fs.existsSync(coverageDir)) {
  console.log('ℹ️  未找到 coverage 目录，跳过时间戳移除')
  process.exit(0)
}

function processDirectory(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true })

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name)

    if (entry.isDirectory()) {
      processDirectory(fullPath)
    } else if (entry.name.endsWith('.html')) {
      let content = fs.readFileSync(fullPath, 'utf8')
      const originalContent = content

      // ✅ 核心逻辑：删除整个包含时间戳的 footer 行
      // 匹配规则：从 "at" 开始到换行符/div结束的所有时间戳相关内容
      content = content.replace(
        /<div class='footer[^']*'>[\s\S]*?at\s+[^<]+<\/div>/g,
        '<div class="footer quiet pad2 space-top1 center small">Code coverage generated by <a href="https://istanbul.js.org/" target="_blank" rel="noopener noreferrer">istanbul</a></div>'
      )

      // 如果内容有变化才写文件，避免不必要的 Git 变动
      if (content !== originalContent) {
        fs.writeFileSync(fullPath, content, 'utf8')
      }
    }
  }
}

processDirectory(coverageDir)
